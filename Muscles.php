        <div class="blog-news-details blog-single-details" style="max-width:100%; margin-left:auto; margin-right:auto;">
          <h2>What is a muscle ?</h2>
          <p>Muscle is a soft tissue found in most animals. Muscle cells contain protein filaments of actin and myosin
            that slide past one another, producing a contraction that changes both the length and the shape of the
            cell. Muscles function to produce force and motion. They are primarily responsible for maintaining and
            changing posture, locomotion, as well as movement of internal organs, such as the contraction of the heart
            and the movement of food through the digestive system via peristalsis.</p>
          <h3>Types of Muscle Tissue</h3>
          <p><strong>Skeletal muscle or "voluntary muscle"</strong> is anchored by tendons (or by aponeuroses at a few
            places) to bone and is used to effect skeletal
            movement such as locomotion and in maintaining posture. Though this postural control is generally
            maintained as an unconscious reflex, the muscles responsible react to conscious control like
            non-postural muscles. An average adult male is made up of 42% of skeletal muscle and an average adult
            female is made up of 36% (as a percentage of body mass).</p>
          <p><strong>Cardiac muscle (myocardium)</strong> is also an "involuntary muscle" but is more akin in structure
            to skeletal muscle, and is found only
            in the heart.</p>
          <p><strong>Smooth muscle or "involuntary muscle"</strong> is found within the walls of organs and structures
            such as the esophagus, stomach, intestines,
            bronchi, uterus, urethra, bladder, blood vessels, and the arrector pili in the skin (in which it
            controls erection of body hair). Unlike skeletal muscle, smooth muscle is not under conscious control.</p>
          <p>However our concern will be on Skeletal Muscles.</p>
          <p>Skeletal muscle is composed of thread-like myofibrils and sarcomeres that form a muscle fiber and are
            the basic units of contraction.</p>
          <p>The 650 skeletal muscles in the human body contract when they receive signals from motor neurons,
            which are triggered from a part of the cell called the sarcoplasmic reticulum. Motor neurons tell your
            muscles to contract and the better you become at having those signals tell your muscles to contract,
            the stronger you can get.</p>
          <p>After you workout, your body repairs or replaces damaged muscle fibers through a cellular process
            where it fuses muscle fibers together to form new muscle protein strands or myofibrils. These repaired
            myofibrils increase in thickness and number to create muscle hypertrophy (growth). Muscle growth
            occurs whenever the rate of muscle protein synthesis is greater than the rate of muscle protein
            breakdown, it occurs while you rest.</p>
          <p>This is where Satellite cells come in and act like stem cells for your muscles. When activated, they
            help to add more nuclie to the muscle cells and therefore contribute directly to the growth of
            myofibrils (muscle cells). Activating these satellite cells may be the difference between those who
            grow “massive muscles” and those who are “hard-gainers”</p>
          <h2>Muscle Strength</h2>
          <p>A display of "strength" (e.g. lifting a weight) is a result of three factors that overlap:</p>
          <p>1. Physiological strength (muscle size, cross sectional area, available crossbridging, responses to
            training).</p>
          <p>2. Neurological strength (how strong or weak is the signal that tells the muscle to contract).</p>
          <p>3. Mechanical strength (muscle's force angle on the lever, moment arm length, joint capabilities).</p>
          <h2>
            Muscle hypertrophy or Muscle grow
          </h2>
          <p>
            It involves an increase in size of skeletal muscle through a growth in size of its component cells. Two
            factors contribute to hypertrophy: sarcoplasmic hypertrophy, which focuses more on increased muscle
            glycogen storage; and myofibrillar hypertrophy, which focuses more on increased myofibril size.
          </p>
          <h2>Sarcoplasmic Hypertrophy</h2>
          <p>
            Sarcoplasmic hypertrophy is an increase in muscle cell fluid within the sarcoplasm. Imagine grabbing a
            handfull of licorice vines. Each licorice vine represents a bundle of muscle fibers. Between the bundles
            is a fluid-filled space called the sarcoplasm. During sarcoplasmic hypertrophy, the sarcoplasmic fluid
            volume increases, but the muscle fiber mass does not, essentially creating larger, less dense muscles. No
            actual muscle growth occurs and no strength is really gained, but the muscle itself appears much
            larger.<br><br>
            Sarcoplasmic hypertrophy occurs from higher rep schemes (10-15+ reps) associated with bodybuilding, where
            building muscle size is the main goal. It is why some people in the gym appear large and muscular but are
            relatively weak.<br><br>For most athletes, training for sarcoplasmic hypertrophy is not beneficial. Only
            high-impact sport athletes like football and rugby players should add this type of training to their
            programs—to gain the additional benefit of size to help reduce injuries due to impact. Most other athlete
            programs should focus on myofibrillar hypertrophy.
          </p>
          <h2>Myofibrillar Hypertrophy</h2>
          <p>Myofibrillar hypertrophy is essentially muscle fiber growth. A myofibril is the contractile portion of a
            muscle fiber. Without myofibrils, our muscles could not move. When myofibrillar hypertrophy takes place,
            the number of myofibrils in a muscle increases, which in turn increases the muscle fiber density and
            strength.<br><br>Again using the example of licorice vines, if you have five vines in your hand, each one
            representing a myofibril within a muscle fiber, you have five contractile units within that muscle fiber.
            Now add three more pieces of licorice, or three more myofibrils. This represents myofibrillar hypertrophy.
            The muscle fiber itself has grown by adding more contractile units, making it bigger and
            stronger.<br><br>Myofibrillar hypertrophy occurs from heavier loads and lower rep schemes (3-5 reps).
            Because it involves the addition of more contractile units to the muscle cells, myofibrillar hypertrophy
            is more beneficial to most athletes than sarcoplasmic hypertrophy. More myofibrils means greater strength
            and power production.
          </p>
          <h2>Conclusion</h2>
          <p>
            If you want to build size, focus on sarcoplasmic hypertrophy and perform higher rep schemes. If strength
            and power are your goals, aim for myofibrillar hypertrophy with heavy weight and low rep schemes.
          </p>
          <br><br>
          <h2># Mechanisms to grow Muscle</h2>
          <p><strong>Muscle Tension:</strong> You have to apply a load of stress greater than what your body or muscles
            had previously adapted too. You
            have to lift progressively heavier weights. It changes the chemistry of the muscle, allowing for growth
            factors that include motor neurons and satellite cell activation.</p>
          <p><strong>Muscle Damage:</strong> After working out there is a local muscle damage that causes a release of
            inflammatory molecules and
            immune system cells that activate satellite cells to jump into action.</p>
          <h3 style="font-size:1.1em;">NOTE : How to know whether “Am I Sore or Injured? ”</h3>
          <p style="font-size:1em;">Post-workout soreness can start anywhere from later that day until a few days after
            the workout,
            depending on the intensity of the workout, with a peak usually around the 36-hour mark. However, after a
            couple of days, the soreness should reduce dramatically.<br><br>To help alleviate soreness and lessen
            the aftereffects of a hard workout, stay active and perform some light stretching or foam rolling during
            the 24-hours following your gym session. This movement will help to circulate blood and nutrients to the
            damaged tissue.<br><br>When pain persists for a longer period of time or causes an extreme restriction
            in movement, you may have crossed the fine line from soreness into injury. It’s likely time for a quick
            check-up with a medical professional.
          </p>
          <p><strong>Metabolic Stress:</strong> Metabolic stress causes cell swelling or “pump” around the muscle, which
            helps to contribute to
            muscle growth without necessarily increasing the size of the muscle cells. This type of growth is known
            as sarcoplasmic hypertrophy and is one of the ways that people can get the appearance of larger
            muscles without increases in strength.</p>
          <p><strong>Hormones:</strong> Insulin Growth Factor (IGF)-1, in particular Mecho-Growth Factor (MGF) and
            Testosterone are the two
            most vital mechanisms that promote muscle growth.<br>Testosterone increases protein synthesis,
            inhibits protein breakdown, activates satellite cells, and stimulates other anabolic hormones.<br>The
            IGF regulates the amount of muscle mass growth by enhancing protein synthesis, facilitating glucose
            uptake, repartitioning the uptake of amino acids (the building blocks of protein) into skeletal
            muscles and once again, activates satellite cells to increase muscle growth.
          </p>
          <p><strong>Nutrition and Rest !</strong> Provide your body with adequate rest or nutrition. The response of
            muscle protein metabolism to a
            resistance exercise bout lasts for 24-48 hours; thus, the interaction between protein metabolism and
            any meals consumed in this period will determine the impact of the diet on muscle hypertrophy. What you
            use to fuel your body is just as important as how hard you push yourself during training. Remember to
            have healthy, whole foods on hand but eat what you need to get through your workouts effectively.
          </p>
